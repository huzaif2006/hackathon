const cors = require('cors')
const express = require('express')
const authRoutes = require('./routes/auth.routes')
const healthRoutes = require('./routes/health.routes')
const organizationRoutes = require('./routes/organization.routes')
const setupRoutes = require('./routes/setup.routes')
const { authenticate, requirePasswordChangeComplete } = require('./middleware/auth.middleware')
const errorHandler = require('./middleware/error.middleware')
const employeeRoutes = require('./routes/employee.routes')
const attendanceRoutes = require('./routes/attendance.routes')
const leaveRoutes = require('./routes/leave.routes')
const notificationRoutes = require('./routes/notification.routes')
const payrollRoutes = require('./routes/payroll.routes')
const dashboardRoutes = require('./routes/dashboard.routes')
const aiRoutes = require('./routes/ai.routes')
const auditRoutes = require('./routes/audit.routes')
const announcementRoutes = require('./routes/announcement.routes')
const ensureDatabase = require('./middleware/ensure-database.middleware')

const app = express()

app.set('trust proxy', 1)
const allowedOrigins = (process.env.FRONTEND_URL || '')
  .split(',')
  .map((origin) => origin.trim())
  .filter(Boolean)
app.use(cors({
  origin(origin, callback) {
    const vercelOrigins = [process.env.VERCEL_URL, process.env.VERCEL_BRANCH_URL]
      .filter(Boolean)
      .map((host) => (host.startsWith('http') ? new URL(host).origin : `https://${host}`))
    const isVercelPreview = typeof origin === 'string'
      && origin.startsWith('https://')
      && origin.endsWith('.vercel.app')
    callback(null, !origin || allowedOrigins.includes(origin) || vercelOrigins.includes(origin) || isVercelPreview)
  },
}))
app.use(express.json())
app.use(ensureDatabase)
app.use('/api', healthRoutes)
app.use('/api/setup', setupRoutes)
app.use('/api/auth', authRoutes)
app.use('/api', authenticate, requirePasswordChangeComplete)
app.use('/api/organization', organizationRoutes)
app.use('/api/employees', employeeRoutes)
app.use('/api/attendance', attendanceRoutes)
app.use('/api/leave', leaveRoutes)
app.use('/api/notifications', notificationRoutes)
app.use('/api/payroll', payrollRoutes)
app.use('/api/dashboard', dashboardRoutes)
app.use('/api/ai', aiRoutes)
app.use('/api/audit-logs', auditRoutes)
app.use('/api/announcements', announcementRoutes)
app.use(errorHandler)

module.exports = app
